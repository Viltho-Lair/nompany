export function field(
  record: Record<string, unknown> | null | undefined,
  base: string,
  locale: string,
): string {
  if (!record) return "";
  const val = record[`${base}_${locale}`];
  if (val != null && String(val).trim() !== "") return String(val);
  return String(record[`${base}_en`] ?? "");
}

